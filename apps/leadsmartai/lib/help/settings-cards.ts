/** The card a guide documents, if it documents one. */
export function cardForGuide(slug: string): SettingsCard | null {
  return SETTINGS_CARDS.find((c) => c.guide === slug) ?? null;
}

/** Cards grouped by tab, in product order, skipping tabs with nothing to show. */
export function cardsByTab(): Array<{ tab: SettingsTab; cards: SettingsCard[] }> {
  return SETTINGS_TABS.map((tab) => ({
    tab,
    cards: SETTINGS_CARDS.filter((c) => c.tab === tab),
  })).filter((g) => g.cards.length > 0);
}

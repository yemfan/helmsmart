/**
 * The Settings page, card by card.
 *
 * Every card an agent can see on /dashboard/settings appears here exactly once,
 * in the order it appears in the product, paired with the guide that explains it
 * and a screenshot of the card itself. This is the list the /help/settings
 * reference page renders, and the source of the screenshot each settings guide
 * shows under "What it looks like".
 *
 * Two rules that keep this honest:
 *
 *  1. One card, one guide. If a card has no guide, it does not belong in the
 *     product — and if a guide covers two cards, agents cannot find either.
 *  2. The screenshots are generated, not hand-cropped. `capture-settings.mjs`
 *     signs into the sandboxed test account, walks the four tabs, and shoots
 *     each card element. Re-run it when the UI changes; do not touch the PNGs
 *     by hand, and never capture from a real agent's account.
 *
 * `Daily Briefings` is absent because it is no longer a Settings card — it
 * moved to Ask Max, where the briefing it schedules actually appears.
 *
 * `Recent calls` is deliberately absent: it renders live call rows with real
 * names and numbers, so it is excluded from capture and has no guide.
 */

